"""Turn the patch author's structured edits into new file content and a unified diff
(docs/ARCHITECTURE.md §11, step 1).

The model never writes a diff: it returns line edits, checked here (one file, lines in range, no
overlap, bounded size), and the diff is generated by difflib. A malformed or ambiguous diff
is never produced. Lines are split on "\\n" only, like git: Python's
`str.splitlines` would also split on characters such as U+2028 and shift every line number.
"""

from __future__ import annotations

import difflib
from collections.abc import Sequence

from git_reviewer.llm.structured import PatchEditOutput

MAX_CHANGED_LINES = 200


class EditError(ValueError):
    """The edits cannot be applied as given."""


def split_lines(text: str) -> list[str]:
    """Lines as git counts them, each keeping its "\\n" (the last one may have none)."""
    parts = text.split("\n")
    lines = [part + "\n" for part in parts[:-1]]
    if parts[-1]:
        lines.append(parts[-1])
    return lines


def numbered(text: str) -> str:
    """The file as shown to the patch author: `   12| code`."""
    return "".join(f"{number:>5}| {line}" for number, line in enumerate(split_lines(text), 1))


def apply_edits(original: str, edits: Sequence[PatchEditOutput], path: str) -> str:
    lines = split_lines(original)
    if lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"  # so that a line added at the end does not join the last one
    count = len(lines)
    result: list[str] = []
    cursor = 0
    previous_end = 0
    changed = 0
    for edit in sorted(edits, key=lambda e: (e.start_line, e.end_line)):
        if edit.path != path:
            raise EditError(f"an edit targets {edit.path!r}; only {path} may be changed")
        start, end = edit.start_line, edit.end_line
        if not (1 <= start <= count + 1 and start - 1 <= end <= count):
            raise EditError(f"edit lines {edit.start_line}-{edit.end_line} are out of range")
        if edit.start_line <= previous_end:
            raise EditError("edits overlap")
        new_lines = split_lines(edit.replacement)
        if new_lines and not new_lines[-1].endswith("\n"):
            new_lines[-1] += "\n"
        result.extend(lines[cursor : edit.start_line - 1])
        result.extend(new_lines)
        changed += len(new_lines) + edit.end_line - edit.start_line + 1
        cursor = max(cursor, edit.end_line)
        previous_end = max(previous_end, edit.end_line)
    result.extend(lines[cursor:])
    if changed > MAX_CHANGED_LINES:
        raise EditError(f"the edits change {changed} lines (limit {MAX_CHANGED_LINES})")
    patched = "".join(result)
    if patched == original:
        raise EditError("the edits change nothing")
    return patched


def unified_diff(path: str, original: str, patched: str) -> str:
    """A git-style unified diff (shown to the user and the auditor; `git apply` accepts it)."""
    out = [f"diff --git a/{path} b/{path}\n"]
    for line in difflib.unified_diff(
        split_lines(original), split_lines(patched), fromfile=f"a/{path}", tofile=f"b/{path}"
    ):
        out.append(line if line.endswith("\n") else line + "\n\\ No newline at end of file\n")
    return "".join(out)


def added_lines(original: str, patched: str) -> list[tuple[int, str]]:
    """(line number in the patched file, text) of every line whose content the patch adds or
    changes. Lines are compared without their "\\n": a last line that only gains one (as
    `apply_edits` gives it) is unchanged."""
    old = [line.removesuffix("\n") for line in split_lines(original)]
    new = [line.removesuffix("\n") for line in split_lines(patched)]
    matcher = difflib.SequenceMatcher(a=old, b=new, autojunk=False)
    found: list[tuple[int, str]] = []
    for tag, _i1, _i2, j1, j2 in matcher.get_opcodes():
        if tag in {"replace", "insert"}:
            found.extend((number + 1, new[number]) for number in range(j1, j2))
    return found
